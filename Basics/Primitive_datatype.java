package com.Madhur.Basics;
// PRIMITIVE DATA TYPE= data type you cant break into further smaller data type like integer/characters
public class Primitive_datatype {
    public static void main(String[] args) {
        // PRIMITIVE data type
        int integers_values = 90;
        char character = 'a';
        long long_integers = 83323L;
        float decimal_numbers = 344.34f;
        double long_decimal_numbers = 364.423323;
        boolean check = true;
        // String is not a primitive data type as it can be break into char data type
        String y = "MADHUR";
    }
}
